import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { compile } from 'svelte/compiler';
import { build } from 'esbuild';
import postcss from 'postcss';
import tailwind from '@tailwindcss/postcss';
const root = fileURLToPath(new URL('../', import.meta.url));
const result = await build({
  absWorkingDir: root,
  entryPoints: ['ui/src/main.js'],
  bundle: true,
  write: false,
  minify: true,
  format: 'iife',
  platform: 'browser',
  target: ['es2022'],
  conditions: ['svelte', 'browser'],
  plugins: [
    {
      name: 'svelte',
      setup(api) {
        api.onLoad({ filter: /\.svelte$/ }, async ({ path }) => {
          const compiled = compile(await readFile(path, 'utf8'), {
            filename: path,
            generate: 'client',
            css: 'external',
            dev: false,
          });
          for (const warning of compiled.warnings)
            console.warn(`${path}: ${warning.message}`);
          return {
            contents: compiled.js.code,
            loader: 'js',
            resolveDir: dirname(path),
          };
        });
      },
    },
  ],
});
const css = await postcss([
  tailwind({ base: resolve(root, 'ui/src'), optimize: true }),
]).process(await readFile(resolve(root, 'ui/src/app.css'), 'utf8'), {
  from: resolve(root, 'ui/src/app.css'),
});
const script = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><meta name="dbsandbox-token" content="__TOKEN__"><title>dbsandbox</title><style nonce="__TOKEN__">${css.css}</style></head><body><div id="app"></div><script nonce="__TOKEN__">${script}</script></body></html>`;
await mkdir(resolve(root, 'ui/generated'), { recursive: true });
await writeFile(
  resolve(root, 'ui/generated/page.js'),
  `// Generated by bun run build:ui.\nexport const html = ${JSON.stringify(html)};\n`,
);
console.log(
  `Dashboard: ${(Buffer.byteLength(html) / 1024).toFixed(1)} KiB, bundled Svelte + Tailwind + Lucide`,
);
